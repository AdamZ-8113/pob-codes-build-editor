import { spawnSync } from "node:child_process";
import { mkdir, readFile, rm } from "node:fs/promises";
import { isAbsolute, relative, resolve } from "node:path";
import { fileSha256 } from "./release-common.mjs";

const value = (name) => process.argv.find((arg) => arg.startsWith(`--${name}=`))?.slice(name.length + 3);
const archive = resolve(value("archive") ?? (() => { throw new Error("--archive is required"); })());
const recordFile = resolve(value("record") ?? (() => { throw new Error("--record is required"); })());
const inventoryFile = resolve(value("inventory") ?? (() => { throw new Error("--inventory is required"); })());
const output = resolve(value("out") ?? ".runtime/predecessor");
const runtime = resolve(".runtime");
if (relative(runtime, output).startsWith("..") || isAbsolute(relative(runtime, output))) throw new Error("Predecessor output must remain below .runtime");
const record = JSON.parse(await readFile(recordFile, "utf8"));
if (!record.archive || record.archive.sha256 !== await fileSha256(archive)) throw new Error("Predecessor archive hash or durable asset record mismatch");
const expectedAsset = value("asset-id");
if (expectedAsset && Number(expectedAsset) !== record.archive.assetId) throw new Error("Predecessor archive asset ID mismatch");
const expectedGeneration = value("generation");
if (expectedGeneration && expectedGeneration !== record.generation) throw new Error("Predecessor generation mismatch");
await rm(output, { recursive: true, force: true });
await mkdir(output, { recursive: true });
const extracted = spawnSync("tar", ["-xzf", archive, "-C", output], { stdio: "inherit", windowsHide: true });
if (extracted.error || extracted.status !== 0) throw new Error(extracted.error?.message ?? `tar exited ${extracted.status}`);
const verified = spawnSync(process.execPath, ["scripts/verify-release-record.mjs", `--root=${resolve(output, "import2-release")}`, `--record=${recordFile}`, `--inventory=${inventoryFile}`, `--archive=${archive}`], { stdio: "inherit", windowsHide: true });
if (verified.error || verified.status !== 0) throw new Error(verified.error?.message ?? `predecessor verification exited ${verified.status}`);
console.log(resolve(output, "import2-release"));
